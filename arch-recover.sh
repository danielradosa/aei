#!/usr/bin/env bash

# 

# arch-recover.sh — Finish what phase 3 didn’t.

# 

# Idempotent: run as many times as you need. Skips anything already done.

# Run this as your normal user, NOT as root.

set -uo pipefail

GREEN=’\033[1;32m’; YELLOW=’\033[1;33m’; RED=’\033[1;31m’; CYAN=’\033[1;36m’; RESET=’\033[0m’
log()  { printf “${GREEN}[+]${RESET} %s\n” “$*”; }
warn() { printf “${YELLOW}[!]${RESET} %s\n” “$*”; }
err()  { printf “${RED}[x]${RESET} %s\n” “$*”; }
hr()   { printf “${CYAN}──────────────────────────────────────────────${RESET}\n”; }

[[ $EUID -eq 0 ]] && { err “Run as your user, not root.”; exit 1; }

hr
log “Starting recovery…”
hr

# ── 1. oh-my-zsh + plugins ──────────────────────────────────────────────────

if [[ ! -d “$HOME/.oh-my-zsh” ]]; then
log “Installing oh-my-zsh (unattended)…”
sh -c “$(curl -fsSL https://raw.githubusercontent.com/ohmyzsh/ohmyzsh/master/tools/install.sh)” “” –unattended –keep-zshrc
else
log “oh-my-zsh already present — skipping.”
fi

CUSTOM=”${ZSH_CUSTOM:-$HOME/.oh-my-zsh/custom}”
if [[ ! -d “$CUSTOM/plugins/zsh-autosuggestions” ]]; then
log “Cloning zsh-autosuggestions…”
git clone –depth=1 https://github.com/zsh-users/zsh-autosuggestions “$CUSTOM/plugins/zsh-autosuggestions”
fi
if [[ ! -d “$CUSTOM/plugins/zsh-syntax-highlighting” ]]; then
log “Cloning zsh-syntax-highlighting…”
git clone –depth=1 https://github.com/zsh-users/zsh-syntax-highlighting.git “$CUSTOM/plugins/zsh-syntax-highlighting”
fi

# ── 2. .zshrc with pywal + plugins ──────────────────────────────────────────

if [[ ! -f “$HOME/.zshrc” ]] || ! grep -q “zsh-autosuggestions” “$HOME/.zshrc” 2>/dev/null; then
log “Writing .zshrc…”
cat > “$HOME/.zshrc” <<‘ZSHRC’
export ZSH=”$HOME/.oh-my-zsh”
ZSH_THEME=“agnoster”
plugins=(git sudo command-not-found z fzf docker docker-compose npm node python pip
zsh-autosuggestions zsh-syntax-highlighting)
source $ZSH/oh-my-zsh.sh

[ -f “$HOME/.cache/wal/sequences” ] && cat “$HOME/.cache/wal/sequences”
[ -f “$HOME/.cache/wal/colors-tty.sh” ] && source “$HOME/.cache/wal/colors-tty.sh”

export EDITOR=nvim
export VISUAL=nvim
alias v=nvim
alias vi=nvim
alias ll=‘eza -lah –icons –git’
alias ls=‘eza –icons’
alias cat=‘bat –paging=never’
alias cd=‘z’
command -v zoxide >/dev/null && eval “$(zoxide init zsh)”

export PATH=”$HOME/.local/bin:$PATH”
ZSHRC
else
log “.zshrc already configured — skipping.”
fi

# ── 3. python-pywalfox (AUR — script may have skipped this) ─────────────────

if ! command -v pywalfox >/dev/null 2>&1; then
log “Installing python-pywalfox via paru…”
paru -S –needed –noconfirm python-pywalfox || warn “pywalfox install failed — Firefox theming won’t work, continuing.”
else
log “pywalfox already installed.”
fi

# ── 4. LazyVim with language extras ─────────────────────────────────────────

if [[ ! -d “$HOME/.config/nvim” ]] || [[ -z “$(ls -A “$HOME/.config/nvim” 2>/dev/null)” ]]; then
log “Bootstrapping LazyVim…”
mkdir -p “$HOME/.config/nvim”
git clone –depth=1 https://github.com/LazyVim/starter “$HOME/.config/nvim”
rm -rf “$HOME/.config/nvim/.git”
cat > “$HOME/.config/nvim/lua/plugins/extras.lua” <<‘LUA’
return {
{ import = “lazyvim.plugins.extras.lang.typescript” },
{ import = “lazyvim.plugins.extras.lang.json” },
{ import = “lazyvim.plugins.extras.lang.yaml” },
{ import = “lazyvim.plugins.extras.lang.toml” },
{ import = “lazyvim.plugins.extras.lang.markdown” },
{ import = “lazyvim.plugins.extras.lang.python” },
{ import = “lazyvim.plugins.extras.lang.rust” },
{ import = “lazyvim.plugins.extras.lang.go” },
{ import = “lazyvim.plugins.extras.lang.php” },
{ import = “lazyvim.plugins.extras.lang.tailwind” },
{ import = “lazyvim.plugins.extras.lang.docker” },
{ import = “lazyvim.plugins.extras.lang.git” },
{ import = “lazyvim.plugins.extras.lang.sql” },
{ import = “lazyvim.plugins.extras.lang.bash” },
{ import = “lazyvim.plugins.extras.editor.harpoon2” },
{ import = “lazyvim.plugins.extras.formatting.prettier” },
{ import = “lazyvim.plugins.extras.linting.eslint” },
}
LUA
log “Running headless Lazy sync (3-5 min)…”
nvim –headless ‘+Lazy! sync’ +qa || warn “Lazy sync had errors — non-fatal.”
else
log “nvim config exists — skipping.”
fi

# ── 5. Themed hyprland.conf (BACKING UP THE CURRENT ONE) ────────────────────

HYPR_CONF=”$HOME/.config/hypr/hyprland.conf”
if [[ -f “$HYPR_CONF” ]] && grep -q “AUTOGENERATED HYPRLAND CONFIG” “$HYPR_CONF” 2>/dev/null; then
log “Backing up default hyprland.conf to hyprland.conf.default…”
cp “$HYPR_CONF” “$HOME/.config/hypr/hyprland.conf.default”
fi

mkdir -p “$HOME/.config/hypr”
log “Writing themed hyprland.conf…”
cat > “$HYPR_CONF” <<‘HYPR’

# ── Themed Hyprland config (recovery) ──────────────────────────────────────

monitor=,preferred,auto,1

$mod  = SUPER
$term = kitty
$menu = rofi -show drun

source = ~/.cache/wal/colors-hyprland.conf

input {
