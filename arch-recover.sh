  border: none;
  border-radius: 0;
  font-family: “JetBrainsMono Nerd Font”, monospace;
  font-size: 13px;
  min-height: 0;
  }

window#waybar {
background: alpha(@background, 0.85);
color: @foreground;
}

#workspaces button {
padding: 0 10px;
background: transparent;
color: @color8;
border-bottom: 2px solid transparent;
}
#workspaces button.active {
color: @foreground;
border-bottom: 2px solid @color4;
}

#window, #clock, #cpu, #memory, #network, #pulseaudio, #battery, #tray {
padding: 0 12px;
color: @foreground;
}

#battery.warning  { color: @color3; }
#battery.critical { color: @color1; }
EOF
fi

# ── 10. Wallpaper (if missing) ──────────────────────────────────────────────

mkdir -p “$HOME/Pictures/wallpapers”
if [[ ! -f “$HOME/Pictures/wallpapers/default.jpg” ]]; then
log “Generating fallback wallpaper…”
if command -v convert >/dev/null 2>&1; then
convert -size 1920x1080 gradient:’#1a1b26-#414868’ “$HOME/Pictures/wallpapers/default.jpg” || true
fi
fi

# Re-seed pywal against the wallpaper so colors-waybar.css etc. exist

if [[ -f “$HOME/Pictures/wallpapers/default.jpg” ]]; then
log “Re-seeding pywal…”
wal -i “$HOME/Pictures/wallpapers/default.jpg” -n -s -t -e -q || warn “pywal seed had issues”
fi

# Firefox theming bridge (best effort)

if command -v pywalfox >/dev/null 2>&1; then
pywalfox install >/dev/null 2>&1 || true
pywalfox update  >/dev/null 2>&1 || true
fi

hr
log “Recovery done.”
log “Now reload Hyprland to pick up the new config:”
log “    hyprctl reload”
log “”
log “Or, if reload doesn’t bring up Waybar, fully restart Hyprland:”
log “  1) Switch to TTY:  Ctrl+Alt+F2”
log “  2) Log in as daniel”
log “  3) pkill Hyprland”
log “  4) tuigreet returns; pick Hyprland; log in”
hr